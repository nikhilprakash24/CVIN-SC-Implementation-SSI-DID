def level_track(x, y, tw, level, words, fav):
    """A 3-slot ordinal track: baseline, three ticks, filled marker at `level`,
    hollow at the others, with the level's word under it. Position is primary."""
    out = []
    pts = [x + 6, x + tw / 2, x + tw - 6]
    out.append(line(pts[0], y, pts[2], y, color=AXIS, sw=1.0))
    for j, px in enumerate(pts):
        if j == level:
            # filled marker at the level; green outline when this level is the favourable end
            out.append(circle(px, y, 4.6, fill=S1, stroke=(S3 if j == fav else INK), sw=1.4 if j == fav else 1.1))
        else:
            tick_fav = (j == fav)
            out.append(circle(px, y, 2.2, fill=(SURFACE), stroke=(S3 if tick_fav else AXIS), sw=1.1))
    out.append(text(x + tw / 2, y + 13, words[level], size=6.1, color=INK, anchor="middle", weight="bold"))
    # tiny 'good end' tick label
    return "".join(out)


