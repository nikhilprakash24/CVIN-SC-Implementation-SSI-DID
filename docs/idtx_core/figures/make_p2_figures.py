# ---------------------------------------------------------------- SVG helpers
def esc(s):
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def doc(w, h, body, title):
    """Wrap figure body in a complete SVG with a light surface card and arrow markers."""
    return (
        '<?xml version="1.0" encoding="utf-8" standalone="no"?>\n'
        '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
        f'width="{w}" height="{h}" viewBox="0 0 {w} {h}" version="1.1">\n'
        f"  <title>{esc(title)}</title>\n"
        '  <desc>Generated by make_p2_figures.py (stdlib SVG). Author: Nikhil Prakash (MASc, UBC ECE).</desc>\n'
        '  <defs>\n'
        '    <style type="text/css">*{stroke-linejoin:round;stroke-linecap:round}</style>\n'
        f'    <marker id="ar" markerWidth="9" markerHeight="9" refX="7" refY="3" orient="auto" markerUnits="userSpaceOnUse"><path d="M0,0 L7,3 L0,6 z" fill="{INK2}"/></marker>\n'
        f'    <marker id="arb" markerWidth="9" markerHeight="9" refX="7" refY="3" orient="auto" markerUnits="userSpaceOnUse"><path d="M0,0 L7,3 L0,6 z" fill="{S1}"/></marker>\n'
        '  </defs>\n'
        f'  <rect x="0" y="0" width="{w}" height="{h}" fill="{SURFACE}"/>\n'
        + body
        + "\n</svg>\n"
    )


def text(x, y, s, size=9, color=INK, anchor="start", weight="normal", style="normal"):
    return (f'<text x="{x:.1f}" y="{y:.1f}" font-family="{FONT}" font-size="{size}" '
            f'fill="{color}" text-anchor="{anchor}" font-weight="{weight}" font-style="{style}">{esc(s)}</text>')


def lines(x, y, rows, size=8, color=INK2, anchor="start", lh=None, weight="normal"):
    lh = lh or size + 3
    return "".join(text(x, y + i * lh, r, size, color, anchor, weight) for i, r in enumerate(rows))


def rrect(x, y, w, h, r=6, fill=SURFACE, stroke=INK, sw=1.3, dash=None, op=None):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    o = f' fill-opacity="{op}"' if op is not None else ""
    return (f'<rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" rx="{r}" ry="{r}" '
            f'fill="{fill}"{o} stroke="{stroke}" stroke-width="{sw}"{d}/>')


def line(x1, y1, x2, y2, color=INK2, sw=1.2, dash=None, arrow=False, marker="ar"):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    a = f' marker-end="url(#{marker})"' if arrow else ""
    return (f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" '
            f'stroke="{color}" stroke-width="{sw}"{d}{a}/>')


def circle(cx, cy, r, fill="none", stroke=INK, sw=1.3):
    return f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r:.1f}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>'


def footer(w, y, parts):
    return lines(14, y, parts, size=7.2, color=MUTED, lh=10)


def title_block(x, y, title, sub=None):
    out = text(x, y, title, size=12.5, color=INK, weight="bold")
    if sub:
        out += text(x, y + 15, sub, size=8.6, color=INK2)
    return out


def _wrap(s, n):
    out, cur = [], ""
    for word in s.split():
        if len(cur) + len(word) + 1 > n:
            out.append(cur)
            cur = word
        else:
            cur = (cur + " " + word).strip()
    if cur:
        out.append(cur)
    return out


