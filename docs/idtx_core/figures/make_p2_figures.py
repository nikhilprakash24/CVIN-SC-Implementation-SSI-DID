def cls_glyph(cx, cy, kind, color, s=5.5):
    """Four distinct shapes — square (Native), half-disc (Composed), open ring
    (Absent), diagonal slash (n-a)."""
    if kind == "square":
        return (f'<rect x="{cx-s:.1f}" y="{cy-s:.1f}" width="{2*s:.1f}" height="{2*s:.1f}" rx="1.5" '
                f'fill="{color}" stroke="{INK}" stroke-width="1"/>')
    if kind == "half":
        half = (f'<path d="M{cx:.1f},{cy-s:.1f} A {s:.1f} {s:.1f} 0 0 0 {cx:.1f},{cy+s:.1f} Z" fill="{color}"/>')
        return half + circle(cx, cy, s, fill="none", stroke=INK, sw=1.1)
    if kind == "open":
        return circle(cx, cy, s, fill=SURFACE, stroke=color, sw=1.4)
    if kind == "slash":
        return (f'<line x1="{cx-s:.1f}" y1="{cy+s:.1f}" x2="{cx+s:.1f}" y2="{cy-s:.1f}" '
                f'stroke="{color}" stroke-width="1.6"/>')
    return circle(cx, cy, s, fill=color, stroke=INK, sw=1)


