def main():
    check = "--check" in sys.argv
    stale = []
    for fn in FIGS:
        name, svg = fn()
        p = OUT / name
        if check:
            if not p.exists() or p.read_text() != svg:
                stale.append(name)
        else:
            p.write_text(svg)
    md = markdown()
    mdp = OUT / "FIGURES_P2.md"
    if check:
        if not mdp.exists() or mdp.read_text() != md:
            stale.append("FIGURES_P2.md")
