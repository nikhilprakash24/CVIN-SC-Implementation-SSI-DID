def bp001():
    s = Sheet("BP-001", "General arrangement — the layer ladder", "Inboard profile: what the identity system rests on, deck by deck",
              notes=["Decks L0–L2 are not implemented in this repository; they are the trust base (THREAT_MODEL §3, T1).",
                     "Decks L3–L6 are implemented and measured here. Each deck's sheet names what it inherits from below.",
                     "A transaction on L4 is an ordinary transaction on L2: same validators, same finality, same fee market as a value transfer."],
              refs=["docs/THREAT_MODEL.md §1–3 (system model, trust assumptions)", "docs/blueprints/PLAN_1_BLUEPRINT_PROGRAMME.md §2",
                    "docs/blueprints/SECURITY_GUARANTEE_INHERITANCE.md"])
    x, y = INNER[0] + 40, INNER[1] + 150
    w, h = 1180, 82
    ptr = {"L6": "BP-302, BP-601", "L5": "BP-201 … BP-205", "L4": "BP-103 … BP-106", "L3": "BP-102", "L2": "BP-402", "L1": "BP-402", "L0": "BP-101"}
    for i, (deck, name, contents, supplies) in enumerate(LAYERS):
        yy = y + i * (h + 6)
        impl = deck in ("L3", "L4", "L5", "L6")
        stroke = LINE if impl else LINE_SOFT
        s.rect(x, yy, w, h, stroke=stroke, sw=2.4 if impl else 1.6, fill=GROUND_DK if impl else "none")
        s.text(x + 14, yy + 32, deck, size=22, weight="bold", mono=True, color=ACCENT if impl else LINE_SOFT)
        s.text(x + 14, yy + 50, ptr[deck], size=8, color=LINE_FAINT, mono=True)
        s.text(x + 90, yy + 22, name, size=13, weight="bold", color=stroke, spacing=1)
        s.wrap(x + 90, yy + 42, contents, width_chars=70, size=10, lh=14, color=LINE_SOFT, mono=True)
        s.line(x + 640, yy + 6, x + 640, yy + h - 6, stroke=LINE_FAINT, sw=0.8)
        s.text(x + 652, yy + 20, "supplies to the deck above", size=8, color=LINE_FAINT, mono=True)
        s.wrap(x + 652, yy + 38, supplies, width_chars=50, size=11, lh=14, color=LINE)
        s.text(x + w - 12, yy + h - 8, "measured here" if impl else "trust base (assumed)", size=9, anchor="end", color=ACCENT if impl else LINE_FAINT, mono=True)
        if i < len(LAYERS) - 1:
            s.arrow(x + 640, yy + h + 6, x + 640, yy + h + 1, stroke=LINE_SOFT, sw=1.2, head=7)
    # waterline — the boundary of what the thesis implements
    wl = y + 4 * (h + 6) - 3
    s.line(x - 20, wl, x + w + 20, wl, stroke=ACCENT, sw=1.6, dash="12,6")
    s.text(x + w + 24, wl + 4, "◄ waterline", size=10, color=ACCENT, mono=True)
    s.text(x + w + 24, wl + 18, "thesis scope boundary", size=9, color=ACCENT, mono=True)
    s.text(x + w + 24, wl + 31, "(THREAT_MODEL §6)", size=9, color=ACCENT, mono=True)
    s.line(x - 22, y, x - 22, y + 4 * (h + 6) - 6, stroke=LINE_SOFT, sw=0.9)
    s.text(x - 26, y + 2 * (h + 6), "4 DECKS BUILT", size=9, color=LINE_SOFT, mono=True, anchor="middle", rotate=-90)
    s.line(x - 22, y + 4 * (h + 6), x - 22, y + 7 * (h + 6) - 6, stroke=LINE_SOFT, sw=0.9)
    s.text(x - 26, y + 5.5 * (h + 6), "3 DECKS ASSUMED", size=9, color=LINE_SOFT, mono=True, anchor="middle", rotate=-90)
    return s


